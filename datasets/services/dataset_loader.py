from pathlib import Path

import pandas as pd


class DatasetLoadError(Exception):
    pass


def load_dataset(file_path, file_type):

    try:

        if file_type == "csv":

            df = pd.read_csv(
                file_path,
                low_memory=False,
            )

        elif file_type == "xlsx":

            df = pd.read_excel(
                file_path
            )

        elif file_type == "json":

            df = pd.read_json(
                file_path
            )

        else:

            raise DatasetLoadError(
                "Unsupported dataset type."
            )

    except Exception as exc:

        raise DatasetLoadError(
            f"Unable to read dataset: {exc}"
        ) from exc

    if df.empty:

        raise DatasetLoadError(
            "The uploaded dataset is empty."
        )

    if len(df.columns) == 0:

        raise DatasetLoadError(
            "Dataset contains no columns."
        )

    # Remove completely empty columns
    df = df.dropna(
        axis=1,
        how="all"
    )

    # Normalize column names
    df.columns = [
        str(column).strip()
        for column in df.columns
    ]

    # Remove unnamed columns generated by Excel/CSV
    df = df.loc[
        :,
        [
            column
            for column in df.columns
            if column
            and not column.lower().startswith("unnamed:")
        ],
    ]

    if df.empty:

        raise DatasetLoadError(
            "No usable columns were found."
        )

    # Make duplicate column names unique
    df.columns = make_unique_columns(
        df.columns.tolist()
    )

    return df


def make_unique_columns(columns):

    seen = {}
    result = []

    for column in columns:

        base = column or "column"

        if base not in seen:

            seen[base] = 0
            result.append(base)

        else:

            seen[base] += 1

            result.append(
                f"{base}_{seen[base]}"
            )

    return result